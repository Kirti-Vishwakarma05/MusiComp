/* Merge LLM enrichment ({e,d} JSONL batches) into questions.js.
   Usage: node enrich_questions.js  (reads /tmp/enrich_full.jsonl + /tmp/enrich_retry.jsonl)
   Rows map to bank indices via the "#N" prefix embedded in each batch input. */
"use strict";
const fs = require("fs");
const path = require("path");

global.window = {};
eval(fs.readFileSync(path.join(__dirname, "questions.js"), "utf8"));
const BANK = window.QUESTION_BANK;

const FILES = ["/tmp/enrich_full.jsonl", "/tmp/enrich_retry.jsonl", "/tmp/enrich_retry2.jsonl"];
let applied = 0, bad = 0;
const seen = new Set();

for (const f of FILES) {
  if (!fs.existsSync(f)) continue;
  for (const line of fs.readFileSync(f, "utf8").split("\n")) {
    if (!line.trim()) continue;
    let r;
    try { r = JSON.parse(line); } catch { bad++; continue; }
    if (r.error || !r.input || !r.output) continue;
    const m = /^#(\d+)/.exec(r.input);
    if (!m) { bad++; continue; }
    const idx = Number(m[1]);
    if (!BANK[idx]) { bad++; continue; }
    let o;
    try { o = JSON.parse(r.output); } catch { bad++; continue; }
    if (typeof o.e !== "string" || !o.e.trim()) { bad++; continue; }
    const d = Math.min(3, Math.max(1, Number(o.d) || 2));
    BANK[idx].e = o.e.trim();
    BANK[idx].d = d;
    seen.add(idx);
    applied++;
  }
}

const missing = BANK.map((q, i) => (q.e ? -1 : i)).filter(i => i >= 0);
console.log(`applied=${applied} bad=${bad} covered=${seen.size}/${BANK.length} missing=${missing.length}`);
if (missing.length) console.log("first missing:", missing.slice(0, 25).join(","));
if (process.argv.includes("--write")) {
  const header = "/* Musicomp question bank — 1,000+ CS fundamentals.\n   {cat,q,opts[4],a:correctIndex,e:explanation,d:difficulty 1-3}\n   Generated by gen_questions.js; enriched (e/d fields) by enrich_questions.js. */\n";
  fs.writeFileSync(path.join(__dirname, "questions.js"),
    header + "window.QUESTION_BANK=" + JSON.stringify(BANK) + ";\n");
  console.log("questions.js rewritten:", fs.statSync(path.join(__dirname, "questions.js")).size, "bytes");
} else {
  console.log("(dry run — pass --write to rewrite questions.js)");
}
